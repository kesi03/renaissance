using System.IO.MemoryMappedFiles;

namespace Renaissance.Core.Audio;

/// <summary>
/// Real-time safe bridge between the DAW audio thread and the plugin host process.
/// Audio/MIDI/automation travel through shared memory; the only synchronisation on the
/// audio thread is a bounded wait on a kernel event. No managed allocation happens in Process.
/// One side creates the block (<see cref="AudioBridge(string,int,int,int)"/>), others attach with <see cref="Attach"/>.
/// </summary>
public sealed unsafe class AudioBridge : IDisposable
{
    private readonly MemoryMappedFile _mmf;
    private readonly MemoryMappedViewAccessor _view;
    private readonly EventWaitHandle _go;
    private readonly EventWaitHandle _done;
    private byte* _base;
    private int _faulted;
    private long _faultTick;

    public AudioBridge(string name, int maxFrames, int inputs, int outputs)
        : this(name, maxFrames, inputs, outputs, create: true)
    {
    }

    private AudioBridge(string name, int maxFrames, int inputs, int outputs, bool create)
    {
        Name = name;
        Layout = new AudioLayout(maxFrames, inputs, outputs);
        if (create)
        {
            _mmf = MemoryMappedFile.CreateNew(name, Layout.TotalSize);
            _go = new EventWaitHandle(false, EventResetMode.AutoReset, AudioLayout.GoEventName(name));
            _done = new EventWaitHandle(false, EventResetMode.AutoReset, AudioLayout.DoneEventName(name));
        }
        else
        {
            _mmf = MemoryMappedFile.OpenExisting(name);
            _go = EventWaitHandle.OpenExisting(AudioLayout.GoEventName(name));
            _done = EventWaitHandle.OpenExisting(AudioLayout.DoneEventName(name));
        }
        _view = _mmf.CreateViewAccessor(0, Layout.TotalSize);
        _view.SafeMemoryMappedViewHandle.AcquirePointer(ref _base);
    }

    /// <summary>Opens a block created by another process (used by the DAW-facing wrapper DLL).</summary>
    public static AudioBridge Attach(string name, int maxFrames, int inputs, int outputs, bool autoRetry = true) =>
        new(name, maxFrames, inputs, outputs, create: false) { AutoRetry = autoRetry };

    public string Name { get; }
    public AudioLayout Layout { get; }
    public int TimeoutMs { get; set; } = 250;

    /// <summary>When faulted, periodically try one short block so playback resumes after a host restart.</summary>
    public bool AutoRetry { get; set; }
    public int RetryIntervalMs { get; set; } = 500;
    public int TrialTimeoutMs { get; set; } = 15;

    /// <summary>Incoming MIDI (DAW → plugin). Single producer.</summary>
    public SpscRing<MidiEvent> MidiIn { get; } = new(2048);

    /// <summary>Outgoing MIDI generated by the plugin (plugin → DAW). Single consumer.</summary>
    public SpscRing<MidiEvent> MidiOut { get; } = new(2048);

    /// <summary>Sample-accurate automation (DAW → plugin).</summary>
    public SpscRing<ParamEvent> ParamIn { get; } = new(2048);

    public bool Faulted
    {
        get => Volatile.Read(ref _faulted) != 0;
        set
        {
            if (value) Volatile.Write(ref _faultTick, Environment.TickCount64);
            Volatile.Write(ref _faulted, value ? 1 : 0);
            if (!value) _done.Reset();
        }
    }

    // ---------------------------------------------------------------- managed buffers

    public bool Process(float[][] inputs, float[][] outputs, int frames)
    {
        var offset = 0;
        var ok = true;
        while (offset < frames)
        {
            var n = Math.Min(Layout.MaxFrames, frames - offset);
            ok &= ProcessChunk(inputs, outputs, offset, n);
            offset += n;
        }
        return ok;
    }

    private bool ProcessChunk(float[][] inputs, float[][] outputs, int offset, int n)
    {
        if (!BeginBlock(out var timeout))
        {
            for (var ch = 0; ch < outputs.Length; ch++) outputs[ch].AsSpan(offset, n).Clear();
            return false;
        }

        PrepareBlock(n);
        for (var ch = 0; ch < Layout.Inputs; ch++)
        {
            var dst = new Span<float>(_base + Layout.InputChannelOffset(ch), n);
            if (inputs.Length == 0) dst.Clear();
            else inputs[Math.Min(ch, inputs.Length - 1)].AsSpan(offset, n).CopyTo(dst);
        }

        if (!RunBlock(timeout))
        {
            for (var ch = 0; ch < outputs.Length; ch++) outputs[ch].AsSpan(offset, n).Clear();
            return false;
        }

        for (var ch = 0; ch < outputs.Length; ch++)
        {
            var dst = outputs[ch].AsSpan(offset, n);
            if (Layout.Outputs > 0)
                new Span<float>(_base + Layout.OutputChannelOffset(Math.Min(ch, Layout.Outputs - 1)), n).CopyTo(dst);
            else if (ch < inputs.Length) inputs[ch].AsSpan(offset, n).CopyTo(dst);
            else dst.Clear();
        }
        CollectMidiOut();
        return true;
    }

    // ---------------------------------------------------------------- native buffers (VST2 wrapper)

    /// <summary>Zero-copy-friendly entry for native hosts that hand us float** buffers.</summary>
    public bool ProcessNative(float** inputs, int inputChannels, float** outputs, int outputChannels, int frames)
    {
        var offset = 0;
        var ok = true;
        while (offset < frames)
        {
            var n = Math.Min(Layout.MaxFrames, frames - offset);
            ok &= ProcessNativeChunk(inputs, inputChannels, outputs, outputChannels, offset, n);
            offset += n;
        }
        return ok;
    }

    private bool ProcessNativeChunk(float** inputs, int inCh, float** outputs, int outCh, int offset, int n)
    {
        if (!BeginBlock(out var timeout))
        {
            for (var ch = 0; ch < outCh; ch++) new Span<float>(outputs[ch] + offset, n).Clear();
            return false;
        }

        PrepareBlock(n);
        for (var ch = 0; ch < Layout.Inputs; ch++)
        {
            var dst = new Span<float>(_base + Layout.InputChannelOffset(ch), n);
            if (inCh == 0 || inputs == null) dst.Clear();
            else new ReadOnlySpan<float>(inputs[Math.Min(ch, inCh - 1)] + offset, n).CopyTo(dst);
        }

        if (!RunBlock(timeout))
        {
            for (var ch = 0; ch < outCh; ch++) new Span<float>(outputs[ch] + offset, n).Clear();
            return false;
        }

        for (var ch = 0; ch < outCh; ch++)
        {
            var dst = new Span<float>(outputs[ch] + offset, n);
            if (Layout.Outputs > 0)
                new ReadOnlySpan<float>(_base + Layout.OutputChannelOffset(Math.Min(ch, Layout.Outputs - 1)), n).CopyTo(dst);
            else if (ch < inCh) new ReadOnlySpan<float>(inputs[ch] + offset, n).CopyTo(dst);
            else dst.Clear();
        }
        CollectMidiOut();
        return true;
    }

    // ---------------------------------------------------------------- shared block plumbing

    private bool BeginBlock(out int timeout)
    {
        timeout = TimeoutMs;
        if (!Faulted) return true;
        if (!AutoRetry || Environment.TickCount64 - Volatile.Read(ref _faultTick) < RetryIntervalMs) return false;
        Faulted = false;
        timeout = TrialTimeoutMs;
        return true;
    }

    private void PrepareBlock(int n)
    {
        var header = (int*)_base;

        var pc = 0;
        var paramBase = (int*)(_base + Layout.ParamInOffset);
        while (pc < AudioLayout.MaxEvents && ParamIn.TryRead(out var p))
        {
            paramBase[pc * 2] = p.Index;
            ((float*)paramBase)[pc * 2 + 1] = p.Value;
            pc++;
        }

        var mc = 0;
        var midiBase = (int*)(_base + Layout.MidiInOffset);
        while (mc < AudioLayout.MaxEvents && MidiIn.TryRead(out var m))
        {
            midiBase[mc * 2] = m.DeltaFrames;
            midiBase[mc * 2 + 1] = m.Packed;
            mc++;
        }

        header[0] = n;
        header[1] = pc;
        header[2] = mc;
        header[3] = 0;
    }

    private bool RunBlock(int timeout)
    {
        _go.Set();
        if (_done.WaitOne(timeout)) return true;
        Faulted = true;
        return false;
    }

    private void CollectMidiOut()
    {
        var header = (int*)_base;
        var outCount = Math.Min(header[3], AudioLayout.MaxEvents);
        var outBase = (int*)(_base + Layout.MidiOutOffset);
        for (var i = 0; i < outCount; i++)
            MidiOut.TryWrite(MidiEvent.Unpack(outBase[i * 2], outBase[i * 2 + 1]));
    }

    public void Dispose()
    {
        Volatile.Write(ref _faulted, 1);
        Volatile.Write(ref _faultTick, long.MaxValue / 2);
        AutoRetry = false;
        if (_base != null)
        {
            _view.SafeMemoryMappedViewHandle.ReleasePointer();
            _base = null;
        }
        _view.Dispose();
        _mmf.Dispose();
        _go.Dispose();
        _done.Dispose();
    }
}
