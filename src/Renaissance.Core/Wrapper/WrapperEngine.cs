using Renaissance.Core.Audio;
using Renaissance.Core.Hosting;
using Renaissance.Core.Models;
using Renaissance.Core.Session;

namespace Renaissance.Core.Wrapper;

/// <summary>
/// All wrapper behaviour lives here so the VST2 and VST3 front-ends stay thin and identical (Rules 1, 2, 9).
/// Methods marked "audio thread" are allocation-free and lock-free.
/// </summary>
public sealed class WrapperEngine : IAsyncDisposable
{
    private readonly ICrashLog? _crashLog;

    public WrapperEngine(ICrashLog? crashLog = null) => _crashLog = crashLog;

    public PluginSession? Session { get; private set; }
    public double SampleRate { get; private set; } = 44100;
    public int BlockSize { get; private set; } = 512;
    public bool IsReady => Session is { IsLoaded: true, IsFaulted: false };

    /// <summary>Raised after the isolated host crashed and was automatically restarted with state restored.</summary>
    public event Action? Recovered;

    public static PluginInfo DescribeFile(string path)
    {
        var pe = PeInspector.Inspect(path);
        if (!pe.IsPe || !pe.ExportsVstEntry) throw new InvalidDataException($"'{path}' is not a VST2 plugin.");
        return new PluginInfo
        {
            Name = System.IO.Path.GetFileNameWithoutExtension(path),
            Path = path,
            Architecture = pe.Architecture,
            HostType = PluginInfo.HostFor(pe.Architecture),
        };
    }

    public async Task LoadPluginAsync(string path, double sampleRate, int blockSize, PluginState? restore = null)
    {
        if (Session is not null) await Session.DisposeAsync().ConfigureAwait(false);
        SampleRate = sampleRate;
        BlockSize = blockSize;
        var session = new PluginSession(DescribeFile(path), _crashLog) { HidePopups = true };
        await session.LoadAsync(restore).ConfigureAwait(false);
        await session.ConfigureAudioAsync(sampleRate, blockSize).ConfigureAwait(false);
        session.Recovered += () => Recovered?.Invoke();
        Session = session;
    }

    public Task ConfigureAsync(double sampleRate, int blockSize)
    {
        SampleRate = sampleRate;
        BlockSize = blockSize;
        return Session is null ? Task.CompletedTask : Session.ConfigureAudioAsync(sampleRate, blockSize);
    }

    // ---------------------------------------------------------------- audio thread

    /// <summary>Audio thread. Mono and stereo buffers are both supported; the bridge adapts channel counts.</summary>
    public bool Process(float[][] inputs, float[][] outputs, int frames)
    {
        var audio = Session?.Audio;
        if (audio is null || !IsReady)
        {
            for (var ch = 0; ch < outputs.Length; ch++) outputs[ch].AsSpan(0, frames).Clear();
            return false;
        }
        return audio.Process(inputs, outputs, frames);
    }

    public bool NoteOn(int channel, int note, int velocity, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.NoteOn(channel, note, velocity, delta)) ?? false;

    public bool NoteOff(int channel, int note, int velocity = 0, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.NoteOff(channel, note, velocity, delta)) ?? false;

    public bool ControlChange(int channel, int controller, int value, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.ControlChange(channel, controller, value, delta)) ?? false;

    public bool PitchBend(int channel, int value14, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.PitchBend(channel, value14, delta)) ?? false;

    public bool Aftertouch(int channel, int pressure, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.Aftertouch(channel, pressure, delta)) ?? false;

    public bool ProgramChange(int channel, int program, int delta = 0) =>
        Session?.Audio?.MidiIn.TryWrite(MidiEvent.ProgramChange(channel, program, delta)) ?? false;

    public bool RawMidi(in MidiEvent e) => Session?.Audio?.MidiIn.TryWrite(e) ?? false;

    /// <summary>Audio thread. Automation from the DAW, applied sample-accurately at the start of the next block.</summary>
    public bool SetParameter(int index, float normalized) =>
        Session?.Audio?.ParamIn.TryWrite(new ParamEvent(index, normalized)) ?? false;

    /// <summary>Drains MIDI generated by the plugin (arpeggiators, sequencers…) for the DAW.</summary>
    public bool TryReadOutgoingMidi(out MidiEvent e)
    {
        var q = Session?.Audio?.MidiOut;
        if (q is null)
        {
            e = default;
            return false;
        }
        return q.TryRead(out e);
    }

    public Task SendSysExAsync(byte[] data) => Session?.SendSysExAsync(data) ?? Task.CompletedTask;

    // ---------------------------------------------------------------- state (Rule 7 / 8)

    /// <summary>Serialised state for DAW project save. Uses Renaissance's maintained copy if the host cannot answer.</summary>
    public byte[] SaveState()
    {
        if (Session is null) return [];
        try { Session.SnapshotAsync().GetAwaiter().GetResult(); }
        catch (Exception ex) when (ex is HostCrashedException or TimeoutException) { }
        return Session.SerializeState();
    }

    public async Task LoadStateAsync(byte[] data, double sampleRate, int blockSize)
    {
        if (data.Length == 0) return;
        var state = PluginState.FromBytes(data);
        if (Session is { IsLoaded: true } && Session.Info.Path.Equals(state.PluginPath, StringComparison.OrdinalIgnoreCase))
            await Session.RestoreStateAsync(state).ConfigureAwait(false);
        else
            await LoadPluginAsync(state.PluginPath, sampleRate, blockSize, state).ConfigureAwait(false);
    }

    public async ValueTask DisposeAsync()
    {
        if (Session is not null) await Session.DisposeAsync().ConfigureAwait(false);
        Session = null;
    }
}
